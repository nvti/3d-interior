const titleCase = (s) => s.toLowerCase().replace(/(^|\s)\S/g, (c) => c.toUpperCase());

/** "FURNITURE - SOFA - CURVE" -> ["Nội thất", "Sofa", "Sofa cong"] */
export function categoryPathFor(folder) {
  const parts = folder.split(" - ").map((s) => s.trim());
  const group = GROUPS[parts[0]] ?? titleCase(parts[0]);
  if (parts.length === 1) return [group];
  return [group, ...(SUB[folder] ?? parts.slice(1).map(titleCase))];
}
